//! Parser for the HTML that arxiv.org/html serves, which LaTeXML generates.
//!
//! Only tables inside table figures (`figure.ltx_table`) are result tables.
//! LaTeXML writes them either as `<table>/<tr>/<td>` or, for resized tables,
//! as `<span class="ltx_tabular|ltx_tr|ltx_td">`; both are read the same way.
//! A tabular nested inside another one is a multi-line cell, not a table.

use scraper::{ElementRef, Html, Node, Selector};
use sota_core::{Cell, Channel, Document, Paragraph, Section, Table};

/// Upper bound on a span attribute, so a malformed `rowspan="99999"` cannot blow up the grid.
const MAX_SPAN: usize = 1000;

pub fn parse(html: &str, arxiv_id: &str, version: u32) -> Document {
    let page = Html::parse_document(html);
    let mut tables = Vec::new();
    let mut unparsed_tables = Vec::new();

    let figures = selector("figure");
    let outer_figures = page
        .select(&figures)
        .filter(|f| is_table_figure(f) && !has_ancestor(f, is_table_figure));
    for figure in outer_figures {
        let figure_id = figure.value().attr("id").unwrap_or_default().to_owned();
        let parts = figure_parts(figure);
        let tabulars: Vec<usize> = (0..parts.len())
            .filter(|&i| matches!(parts[i], Part::Tabular(_)))
            .collect();
        if tabulars.is_empty() {
            unparsed_tables.push(figure_id);
            continue;
        }
        let several = tabulars.len() > 1;
        for (n, &at) in tabulars.iter().enumerate() {
            let Part::Tabular(tabular) = parts[at] else {
                continue;
            };
            let id = if several {
                format!("{figure_id}.t{}", n + 1)
            } else {
                figure_id.clone()
            };
            let (label, caption) = caption_for(figure, &parts, at);
            tables.push(Table {
                id,
                figure_id: figure_id.clone(),
                label,
                caption,
                cells: lay_out(tabular),
                conversion_errors: tabular
                    .descendants()
                    .filter_map(ElementRef::wrap)
                    .any(|e| has_class(&e, "ltx_ERROR")),
            });
        }
    }

    Document {
        arxiv_id: arxiv_id.to_owned(),
        version,
        channel: Channel::ArxivHtml,
        title: page
            .select(&selector("h1.ltx_title_document"))
            .next()
            .map(|h| prose(h))
            .unwrap_or_default(),
        sections: sections(&page),
        tables,
        unparsed_tables,
    }
}

/// The version the page says it is, read from its own `/abs/<id>vN` link.
pub fn stated_version(html: &str, arxiv_id: &str) -> Option<u32> {
    let needle = format!("/abs/{arxiv_id}v");
    let start = html.find(&needle)? + needle.len();
    let digits: String = html[start..]
        .chars()
        .take_while(char::is_ascii_digit)
        .collect();
    digits.parse().ok()
}

/// "LaTeXML oxide (version 0.7.6)", from the generator comment. `None` means
/// the page was not produced by LaTeXML (an error page, for instance).
pub fn generator(html: &str) -> Option<String> {
    let start = html.find("Generated by LaTeXML")? + "Generated by ".len();
    let rest = &html[start..];
    let end = rest.find(" http").or_else(|| rest.find("-->"))?;
    Some(rest[..end].trim().to_owned())
}

// ---------------------------------------------------------------- tables

fn lay_out(tabular: ElementRef) -> Vec<Cell> {
    let rows = rows(tabular);
    let n_rows = rows.len();
    let mut occupied: Vec<Vec<bool>> = vec![Vec::new(); n_rows];
    let mut cells = Vec::new();
    for (r, row) in rows.into_iter().enumerate() {
        let mut c = 0;
        for el in child_elements(row).filter(is_cell) {
            while occupied[r].get(c).copied().unwrap_or(false) {
                c += 1;
            }
            // A row span cannot reach past the last row.
            let row_span = span(&el, "rowspan").min(n_rows - r);
            let col_span = span(&el, "colspan");
            for taken in occupied.iter_mut().skip(r).take(row_span) {
                if taken.len() < c + col_span {
                    taken.resize(c + col_span, false);
                }
                taken[c..c + col_span].fill(true);
            }
            let extract = extract(el, Mode::Cell);
            cells.push(Cell {
                row: r,
                col: c,
                row_span,
                col_span,
                text: extract.text,
                bold: is_bold(el),
                header: el.value().name() == "th"
                    || el.value().classes().any(|k| k.starts_with("ltx_th")),
                cites: extract.cites,
            });
            c += col_span;
        }
    }
    cells
}

fn rows(tabular: ElementRef) -> Vec<ElementRef> {
    let mut out = Vec::new();
    collect_rows(tabular, &mut out);
    out
}

fn collect_rows<'a>(el: ElementRef<'a>, out: &mut Vec<ElementRef<'a>>) {
    for child in child_elements(el) {
        let name = child.value().name();
        if name == "tr" || has_class(&child, "ltx_tr") {
            out.push(child);
        } else if matches!(name, "thead" | "tbody" | "tfoot")
            || ["ltx_thead", "ltx_tbody", "ltx_tfoot"]
                .iter()
                .any(|k| has_class(&child, k))
        {
            collect_rows(child, out);
        }
    }
}

fn is_cell(el: &ElementRef) -> bool {
    matches!(el.value().name(), "td" | "th") || has_class(el, "ltx_td")
}

/// `rowspan="2"` on `<td>`, but `class="ltx_rowspan ltx_rowspan_2"` on the
/// `<span>` cells LaTeXML writes for resized tables.
fn span(el: &ElementRef, attr: &str) -> usize {
    let class_prefix = format!("ltx_{attr}_");
    el.value()
        .attr(attr)
        .map(str::to_owned)
        .or_else(|| {
            el.value()
                .classes()
                .find_map(|c| c.strip_prefix(&class_prefix).map(str::to_owned))
        })
        .and_then(|v| v.trim().parse::<usize>().ok())
        .filter(|&n| n >= 1)
        .unwrap_or(1)
        .min(MAX_SPAN)
}

fn is_bold(el: ElementRef) -> bool {
    el.descendants()
        .filter_map(ElementRef::wrap)
        .any(|e| has_class(&e, "ltx_font_bold") || matches!(e.value().name(), "b" | "strong"))
}

/// Table captions and top-level tabulars of a table figure, in document order.
enum Part<'a> {
    Caption(ElementRef<'a>),
    Tabular(ElementRef<'a>),
}

fn figure_parts(figure: ElementRef) -> Vec<Part> {
    figure
        .descendants()
        .filter_map(ElementRef::wrap)
        .filter_map(|e| {
            if has_class(&e, "ltx_tabular") && !has_ancestor(&e, |a| has_class(a, "ltx_tabular")) {
                Some(Part::Tabular(e))
            } else if e.value().name() == "figcaption" && is_table_caption(&e) {
                Some(Part::Caption(e))
            } else {
                None
            }
        })
        .collect()
}

/// A caption of a table figure, not of a "Figure N" nested inside one.
fn is_table_caption(caption: &ElementRef) -> bool {
    caption
        .ancestors()
        .filter_map(ElementRef::wrap)
        .find(|a| a.value().name() == "figure")
        .is_some_and(|f| is_table_figure(&f))
}

/// (label, caption) for the tabular at `parts[at]`.
///
/// A figure may hold several tables, each with its own caption (A*Net,
/// 2206.04798v5: "Table 1" and "Table 2: Tail prediction ..." side by side),
/// so each table takes its nearest caption: the one before it when the figure
/// puts captions above tables, the one after it when below. A sub-caption such
/// as "(a) ..." keeps the figure's main label and is appended to its caption.
fn caption_for(figure: ElementRef, parts: &[Part], at: usize) -> (String, String) {
    let captions_above = matches!(parts.first(), Some(Part::Caption(_)));
    let caption_at = |i: &usize| match parts[*i] {
        Part::Caption(c) => Some(c),
        Part::Tabular(_) => None,
    };
    let before = (0..at).rev().find_map(|i| caption_at(&i));
    let after = (at + 1..parts.len()).find_map(|i| caption_at(&i));
    let own = if captions_above {
        before.or(after)
    } else {
        after.or(before)
    };
    let Some(own) = own else {
        return (String::new(), String::new());
    };
    let (label, text) = caption_parts(own);
    if label.to_lowercase().starts_with("table") {
        return (label, text);
    }
    // A sub-caption: the label and main text come from the figure's own caption.
    let main = child_elements(figure)
        .find(|c| c.value().name() == "figcaption")
        .or_else(|| {
            parts.iter().find_map(|p| match p {
                Part::Caption(c) if caption_parts(*c).0.to_lowercase().starts_with("table") => {
                    Some(*c)
                }
                _ => None,
            })
        });
    match main {
        Some(main) if main.id() != own.id() => {
            let (main_label, main_text) = caption_parts(main);
            let sub = collapse(&format!("{label} {text}"));
            (main_label, collapse(&format!("{main_text} {sub}")))
        }
        _ => (label, text),
    }
}

/// ("Table 5", caption text without its "Table 5:" tag).
fn caption_parts(caption: ElementRef) -> (String, String) {
    let label = caption
        .descendants()
        .filter_map(ElementRef::wrap)
        .find(|e| has_class(e, "ltx_tag"))
        .map(|tag| prose(tag).trim_end_matches(':').trim().to_owned())
        .unwrap_or_default();
    (label, extract(caption, Mode::Caption).text)
}

// ---------------------------------------------------------------- sections

fn sections(page: &Html) -> Vec<Section> {
    let mut out = Vec::new();
    if let Some(abstract_) = page.select(&selector("div.ltx_abstract")).next() {
        let paragraphs = abstract_
            .select(&selector("p.ltx_p"))
            .enumerate()
            .map(|(n, p)| Paragraph {
                id: format!("abstract.p{}", n + 1),
                text: prose(p),
            })
            .collect();
        out.push(Section {
            id: "abstract".into(),
            heading: "Abstract".into(),
            paragraphs,
        });
    }

    let paragraphs: Vec<ElementRef> = page
        .select(&selector("div.ltx_para"))
        .filter(|p| !has_ancestor(p, |a| a.value().name() == "figure"))
        .collect();
    for section in page.select(&selector("section")) {
        if has_class(&section, "ltx_bibliography") {
            continue;
        }
        let heading = child_elements(section)
            .find(|h| matches!(h.value().name(), "h1" | "h2" | "h3" | "h4" | "h5" | "h6"))
            .map(prose)
            .unwrap_or_default();
        let own = paragraphs
            .iter()
            .filter(|p| nearest_section(p).is_some_and(|s| s.id() == section.id()))
            .enumerate()
            .map(|(n, p)| Paragraph {
                id: p.value().attr("id").map(str::to_owned).unwrap_or_else(|| {
                    format!("{}.p{}", section.value().attr("id").unwrap_or("?"), n + 1)
                }),
                text: prose(*p),
            })
            .collect();
        out.push(Section {
            id: section.value().attr("id").unwrap_or_default().to_owned(),
            heading,
            paragraphs: own,
        });
    }
    out
}

fn nearest_section<'a>(el: &ElementRef<'a>) -> Option<ElementRef<'a>> {
    el.ancestors()
        .filter_map(ElementRef::wrap)
        .find(|a| a.value().name() == "section")
}

// ---------------------------------------------------------------- text

#[derive(Clone, Copy, PartialEq)]
enum Mode {
    /// Table cell: citation markers move to `cites`.
    Cell,
    /// Caption: citations stay inline, the "Table N:" tag is dropped.
    Caption,
    /// Running text: citations stay inline.
    Prose,
}

#[derive(Default)]
struct Extract {
    text: String,
    cites: Vec<String>,
}

fn prose(el: ElementRef) -> String {
    extract(el, Mode::Prose).text
}

fn extract(el: ElementRef, mode: Mode) -> Extract {
    let mut out = Extract::default();
    walk(el, mode, &mut out);
    out.text = collapse(&out.text);
    out
}

fn walk(el: ElementRef, mode: Mode, out: &mut Extract) {
    for child in el.children() {
        match child.value() {
            Node::Text(t) => out.text.push_str(t),
            Node::Element(_) => {
                let Some(c) = ElementRef::wrap(child) else {
                    continue;
                };
                let name = c.value().name();
                if name == "math" {
                    // The LaTeX source is what the author typed: "0.338\pm 0.002".
                    out.text
                        .push_str(c.value().attr("alttext").unwrap_or_default());
                } else if has_class(&c, "ltx_note_outer")
                    || (mode == Mode::Caption && has_class(&c, "ltx_tag"))
                {
                    // Footnote bodies and the "Table N:" tag are not part of the text.
                } else if mode == Mode::Cell && (name == "cite" || has_class(&c, "ltx_cite")) {
                    let marker = prose(c);
                    let marker = marker.trim_matches(|ch: char| "[]() ".contains(ch));
                    if !marker.is_empty() {
                        out.cites.push(marker.to_owned());
                    }
                } else {
                    // Rows and cells of a nested tabular are separate lines of one cell.
                    let block = matches!(name, "tr" | "td" | "th" | "br" | "p" | "div")
                        || has_class(&c, "ltx_tr")
                        || has_class(&c, "ltx_td");
                    if block {
                        out.text.push(' ');
                    }
                    walk(c, mode, out);
                    if block {
                        out.text.push(' ');
                    }
                }
            }
            _ => {}
        }
    }
}

fn collapse(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

// ---------------------------------------------------------------- helpers

fn selector(css: &str) -> Selector {
    Selector::parse(css).expect("static selector")
}

fn has_class(el: &ElementRef, class: &str) -> bool {
    el.value().classes().any(|c| c == class)
}

fn is_table_figure(el: &ElementRef) -> bool {
    el.value().name() == "figure" && has_class(el, "ltx_table")
}

fn has_ancestor(el: &ElementRef, pred: impl Fn(&ElementRef) -> bool) -> bool {
    el.ancestors()
        .filter_map(ElementRef::wrap)
        .any(|a| pred(&a))
}

fn child_elements<'a>(el: ElementRef<'a>) -> impl Iterator<Item = ElementRef<'a>> {
    el.children().filter_map(ElementRef::wrap)
}
